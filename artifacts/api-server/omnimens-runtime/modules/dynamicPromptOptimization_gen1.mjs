import { randomUUID } from 'crypto';

/**
 * Generates an initial population of prompts for optimization.
 * @param {number} populationSize - Number of prompts to generate.
 * @param {Array<string>} baseTemplates - Base templates to start with.
 * @returns {Array<Object>} Array of prompt objects with unique IDs.
 */
export function generateInitialPopulation(populationSize, baseTemplates) {
  const population = [];
  for (let i = 0; i < populationSize; i++) {
    const template = baseTemplates[i % baseTemplates.length];
    population.push({
      id: randomUUID(),
      prompt: template,
      fitness: 0,
    });
  }
  return population;
}

/**
 * Evaluates the fitness of a prompt based on task performance.
 * @param {Object} promptObj - Prompt object containing the prompt text.
 * @param {Function} fitnessFunction - User-defined function to evaluate fitness.
 * @returns {number} Fitness score.
 */
export function evaluateFitness(promptObj, fitnessFunction) {
  try {
    const fitness = fitnessFunction(promptObj.prompt);
    return fitness;
  } catch (error) {
    console.error("Error evaluating fitness:", error);
    return 0;
  }
}

/**
 * Performs crossover between two prompts to generate a new prompt.
 * @param {string} promptA - First parent prompt.
 * @param {string} promptB - Second parent prompt.
 * @returns {string} New prompt generated by combining parts of both parents.
 */
export function crossoverPrompts(promptA, promptB) {
  const midpoint = Math.floor(promptA.length / 2);
  return promptA.slice(0, midpoint) + promptB.slice(midpoint);
}

/**
 * Mutates a prompt to introduce variation.
 * @param {string} prompt - Original prompt.
 * @param {number} mutationRate - Probability of mutation (0-1).
 * @returns {string} Mutated prompt.
 */
export function mutatePrompt(prompt, mutationRate) {
  const characters = prompt.split("");
  for (let i = 0; i < characters.length; i++) {
    if (Math.random() < mutationRate) {
      characters[i] = String.fromCharCode(
        32 + Math.floor(Math.random() * 95) // Random printable ASCII character
      );
    }
  }
  return characters.join("");
}

/**
 * Selects prompts for the next generation based on fitness scores.
 * @param {Array<Object>} population - Current population of prompts.
 * @param {number} selectionSize - Number of prompts to select.
 * @returns {Array<Object>} Selected prompts.
 */
export function selectPromptsByFitness(population, selectionSize) {
  return population
    .sort((a, b) => b.fitness - a.fitness)
    .slice(0, selectionSize);
}

/**
 * Runs the optimization process for a specified number of generations.
 * @param {Array<string>} baseTemplates - Initial templates for prompts.
 * @param {Function} fitnessFunction - Function to evaluate prompt fitness.
 * @param {number} populationSize - Number of prompts in each generation.
 * @param {number} generations - Number of generations to run.
 * @param {number} mutationRate - Probability of mutation.
 * @returns {Object} Best prompt and its fitness score.
 */
export function optimizePrompts(
  baseTemplates,
  fitnessFunction,
  populationSize,
  generations,
  mutationRate
) {
  let population = generateInitialPopulation(populationSize, baseTemplates);

  for (let generation = 0; generation < generations; generation++) {
    // Evaluate fitness
    population = population.map((promptObj) => ({
      ...promptObj,
      fitness: evaluateFitness(promptObj, fitnessFunction),
    }));

    // Select top prompts
    const selectedPrompts = selectPromptsByFitness(population, populationSize / 2);

    // Generate new population via crossover and mutation
    const newPopulation = [];
    for (let i = 0; i < selectedPrompts.length; i++) {
      for (let j = i + 1; j < selectedPrompts.length; j++) {
        const newPrompt = crossoverPrompts(
          selectedPrompts[i].prompt,
          selectedPrompts[j].prompt
        );
        newPopulation.push({
          id: randomUUID(),
          prompt: mutatePrompt(newPrompt, mutationRate),
          fitness: 0,
        });
      }
    }
    population = newPopulation;
  }

  // Return the best prompt
  const bestPrompt = population.sort((a, b) => b.fitness - a.fitness)[0];
  return bestPrompt;
}

